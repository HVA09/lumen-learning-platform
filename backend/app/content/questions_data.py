def mcq(key, prompt, correct, distractors, position, explanation, difficulty=1):
    """الإجابة الصحيحة (correct) تُدرج بين المشتتات (distractors) عند الموضع position (يبدأ من 0)
    — هكذا رقم الإجابة الصحيحة يتحدد تلقائيًا ولا يحصل عدم تطابق، ونوزّع المواضع يدويًا بالتساوي"""
    choices = list(distractors)
    choices.insert(position, correct)
    return {
        "key": key, "kind": "mcq", "prompt_ar": prompt, "choices": choices,
        "correct_answer": position, "tolerance": None,
        "explanation_ar": explanation, "difficulty": difficulty,
    }


def true_false(key, prompt, correct, explanation, difficulty=1):
    return {
        "key": key, "kind": "true_false", "prompt_ar": prompt, "choices": None,
        "correct_answer": correct, "tolerance": None,
        "explanation_ar": explanation, "difficulty": difficulty,
    }


def numeric(key, prompt, correct, explanation, difficulty=1, tolerance=None):
    return {
        "key": key, "kind": "numeric", "prompt_ar": prompt, "choices": None,
        "correct_answer": correct, "tolerance": tolerance,
        "explanation_ar": explanation, "difficulty": difficulty,
    }


def short_text(key, prompt, accepted, explanation, difficulty=1):
    return {
        "key": key, "kind": "short_text", "prompt_ar": prompt, "choices": None,
        "correct_answer": accepted, "tolerance": None,
        "explanation_ar": explanation, "difficulty": difficulty,
    }


